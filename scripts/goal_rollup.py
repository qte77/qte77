#!/usr/bin/env python3
"""Goal-achievement rollup — the lite tracking consumer for the operating model.

Reads goals.json, checks each KR's GitHub Issue state, writes STATUS.md with a
per-goal completion %. Dormant until goals.json has goals. No third-party deps.

Usage:
    python scripts/goal_rollup.py            # print to stdout
    python scripts/goal_rollup.py --write    # (re)write STATUS.md

See docs/goals.md and docs/operating-model.md.
"""
from __future__ import annotations

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPO = "qte77/qte77"


def issue_state(number: int, repo: str = REPO) -> str:
    """Return 'open' / 'closed' / 'unknown' for a GitHub issue via gh."""
    try:
        out = subprocess.run(
            ["gh", "issue", "view", str(number), "--repo", repo, "--json", "state", "--jq", ".state"],
            capture_output=True, text=True, check=True,
        )
        return out.stdout.strip().lower() or "unknown"
    except Exception:  # gh missing / not authed / issue gone — stay dormant, don't crash
        return "unknown"


def render(goals: list) -> str:
    lines = [
        "# Goal status",
        "",
        "*Generated by `scripts/goal_rollup.py` — see [docs/goals.md](docs/goals.md).*",
        "",
    ]
    if not goals:
        lines.append(
            "No goals defined yet — `goals.json` is empty by design (goals are "
            "human-authored; see [docs/goals.md](docs/goals.md)). The rails "
            "(eval-gate, this rollup) are dormant-but-ready."
        )
        return "\n".join(lines) + "\n"
    for g in goals:
        krs = g.get("key_results", [])
        resolved = 0
        achieved = 0
        not_achieved = 0
        inconclusive = 0
        unknown_outcome = 0
        for kr in krs:
            num = kr.get("issue")
            state = issue_state(num) if num else "no-issue"
            outcome = kr.get("outcome")
            if outcome == "achieved":
                achieved += 1
            if state != "closed":
                continue
            resolved += 1
            if outcome == "not-achieved":
                not_achieved += 1
            elif outcome == "inconclusive":
                inconclusive += 1
            elif outcome != "achieved":
                unknown_outcome += 1
        pct = round(100 * achieved / len(krs)) if krs else 0
        resolution_bits = []
        if not_achieved:
            resolution_bits.append(f"{not_achieved} not-achieved")
        if inconclusive:
            resolution_bits.append(f"{inconclusive} inconclusive")
        if unknown_outcome:
            resolution_bits.append(f"{unknown_outcome} outcome unknown")
        resolution_suffix = f" ({', '.join(resolution_bits)})" if resolution_bits else ""
        lines += [
            f"## {g.get('id', '?')} — {g.get('objective', '')}",
            "",
            f"**{pct}%** — {achieved}/{len(krs)} KRs achieved  ·  "
            f"{resolved}/{len(krs)} resolved{resolution_suffix}",
            "",
        ]
        for kr in krs:
            num = kr.get("issue")
            state = issue_state(num) if num else "no-issue"
            outcome = kr.get("outcome")
            mark = "x" if outcome == "achieved" else " "
            ref = f"#{num}" if num else "(unlinked)"
            suffix = ""
            if state == "closed" and outcome != "achieved":
                suffix = f" _(closed, {outcome or 'outcome unknown'})_"
            lines.append(
                f"- [{mark}] `{kr.get('id', '?')}` {ref} — {kr.get('statement', '')}{suffix}"
            )
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    goals = json.loads((ROOT / "goals.json").read_text()).get("goals", [])
    out = render(goals)
    if "--write" in sys.argv:
        (ROOT / "STATUS.md").write_text(out)
        print("wrote STATUS.md")
    else:
        sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
